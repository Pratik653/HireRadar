"""Worldwide location catalog, place detection and selection matching.

The catalog (``app/data/locations.json``) is generated by
``scripts/build_locations.py`` from ISO 3166 codes plus curated hub cities and
aliases. Countries are identified by ISO 3166-1 alpha-2 codes, states and
provinces by ISO 3166-2 codes, and cities by name within their country or
subdivision, so "London, Ontario" and "London, UK" never collide.

Detection works in one pass over the text with a longest-match-first regex,
so "New Jersey" is not read as the island of Jersey and "Papua New Guinea" not
as Guinea. Names that exist in several places are resolved from the rest of the
text (another city, state or country mentioned alongside) and dropped when the
text gives no clue, rather than guessed.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import cache
from pathlib import Path

DATA_FILE = Path(__file__).with_name("data") / "locations.json"

REMOTE_PATTERN = re.compile(r"\b(remote|work from home|wfh|anywhere|distributed)\b", re.I)
HYBRID_PATTERN = re.compile(r"\bhybrid\b", re.I)
ONSITE_PATTERN = re.compile(r"\b(on-?site|in-?office|office based)\b", re.I)
WORLDWIDE_PATTERN = re.compile(r"\b(worldwide|anywhere|global(ly)?|all countries)\b", re.I)
# US/CA/AU state abbreviations as written in location fields: "Austin, TX".
ABBR_COUNTRIES = ("US", "CA", "AU")


@dataclass(frozen=True)
class Place:
    country_code: str
    country: str
    subdivision: str | None = None  # ISO 3166-2 code
    subdivision_name: str | None = None
    city: str | None = None

    @property
    def label(self) -> str:
        parts: list[str] = []
        for part in (self.city, self.subdivision_name, self.country):
            if part and part not in parts:  # "Berlin, Germany", not "Berlin, Berlin, Germany"
                parts.append(part)
        return ", ".join(parts)


@dataclass(frozen=True)
class _Target:
    kind: str  # city | subdivision | country | region
    country: str | None = None
    subdivision: str | None = None
    city: str | None = None
    primary: bool = False
    countries: frozenset[str] = frozenset()
    risky: bool = False


class Catalog:
    def __init__(self, data: dict) -> None:
        self.source = data["source"]
        self.regions: dict[str, dict] = {r["id"]: r for r in data["regions"]}
        self.countries: dict[str, dict] = {c["code"]: c for c in data["countries"]}
        self.subdivisions: dict[str, dict] = {}
        self.cities: dict[tuple[str, str | None], set[str]] = {}
        risky = set(data["risky_words"])

        index: dict[str, list[_Target]] = {}
        cased: dict[str, list[_Target]] = {}
        abbrs: dict[str, list[_Target]] = {}

        def add(alias: str, target: _Target) -> None:
            index.setdefault(alias.lower(), []).append(target)

        def add_cities(code: str, sub: str | None, cities: list[dict]) -> None:
            self.cities[(code, sub)] = {c["name"] for c in cities}
            for city in cities:
                target = _Target("city", code, sub, city["name"], primary=city.get("primary", False))
                for alias in {city["name"].lower(), *city.get("aliases", [])}:
                    add(alias, target)

        for code, country in self.countries.items():
            for alias in country["aliases"]:
                add(alias, _Target("country", code, risky=alias in risky))
            for token in country.get("codes", []):
                cased.setdefault(token, []).append(_Target("country", code))
            add_cities(code, None, country.get("cities", []))
            for sub in country.get("subdivisions", []):
                self.subdivisions[sub["code"]] = {**sub, "country": code}
                target = _Target("subdivision", code, sub["code"])
                for alias in sub["aliases"]:
                    add(alias, target)
                if code in ABBR_COUNTRIES:
                    abbrs.setdefault(sub["abbr"], []).append(target)
                add_cities(code, sub["code"], sub.get("cities", []))

        for alias, members in data["region_aliases"].items():
            add(alias, _Target("region", countries=frozenset(self._expand(members))))

        self._index = index
        self._cased = cased
        self._abbrs = abbrs
        self._pattern = _alternation(index, flags=re.I)
        self._cased_pattern = _alternation(cased, flags=0)
        self._abbr_pattern = re.compile(
            r"(?:,|\s-|\(|^)\s*(" + "|".join(sorted(abbrs, key=len, reverse=True)) + r")(?![A-Za-z])"
        )

    def _expand(self, members: list[str]) -> set[str]:
        out: set[str] = set()
        for member in members:
            out |= set(self.regions[member]["countries"]) if member in self.regions else {member}
        return out

    def region_countries(self, region_id: str) -> set[str]:
        return set(self.regions[region_id]["countries"])

    def country_name(self, code: str) -> str:
        return self.countries[code]["name"]

    def place(self, target: _Target) -> Place:
        sub = self.subdivisions.get(target.subdivision) if target.subdivision else None
        return Place(
            target.country,
            self.country_name(target.country),
            target.subdivision,
            sub["name"] if sub else None,
            target.city,
        )

    # --- detection -------------------------------------------------------------

    def scan(self, text: str, strict: bool = False) -> tuple[list[Place], set[str]]:
        """Return (places, region_countries) mentioned in ``text``.

        ``strict`` is for free text such as a job description: only capitalised
        city and country names count, and short or risky words are ignored.
        Location fields use the default, which also reads "TX"-style state
        abbreviations and upper-case country codes ("UAE", "USA").
        """
        if not text:
            return [], set()
        hits: list[list[_Target]] = []
        regions: set[str] = set()
        for match in self._pattern.finditer(text):
            surface = match.group(0)
            targets = self._index[surface.lower()]
            if strict:
                if not surface[0].isupper() or len(surface) < 4:
                    continue
                targets = [t for t in targets if t.kind in ("city", "country") and not t.risky]
                if not targets:
                    continue
            if targets[0].kind == "region":
                regions |= targets[0].countries
                continue
            hits.append(targets)
        abbr_hits: list[list[_Target]] = []
        if not strict:
            hits += [self._cased[m.group(0)] for m in self._cased_pattern.finditer(text)]
            abbr_hits = [self._abbrs[m.group(1)] for m in self._abbr_pattern.finditer(text)]

        # Context: countries named by hits that have exactly one reading.
        context = {t[0].country for t in hits if len(t) == 1 and not t[0].risky}
        abbr_subs = {t.subdivision for targets in abbr_hits for t in targets}

        resolved: list[_Target] = []
        for targets in hits:
            choice = _resolve(targets, context, abbr_subs)
            if choice is not None:
                resolved.append(choice)
                context.add(choice.country)
        for targets in abbr_hits:
            in_context = [t for t in targets if t.country in context]
            if len(in_context) == 1:
                resolved.append(in_context[0])

        places: dict[tuple, Place] = {}
        for target in resolved:
            place = self.place(target)
            places[(place.country_code, place.subdivision, place.city)] = place
        return _most_specific(list(places.values())), regions


def _alternation(index: dict[str, list], flags: int) -> re.Pattern[str]:
    alternatives = "|".join(re.escape(a) for a in sorted(index, key=len, reverse=True))
    return re.compile(r"(?<![\w])(" + alternatives + r")(?![\w])", flags)


def _resolve(targets: list[_Target], context: set[str], abbr_subs: set[str | None]) -> _Target | None:
    if len(targets) == 1:
        return targets[0]
    by_sub = [t for t in targets if t.subdivision and t.subdivision in abbr_subs]
    if len(by_sub) == 1:
        return by_sub[0]
    by_country = [t for t in targets if t.country in context]
    if len(by_country) == 1:
        return by_country[0]
    pool = by_country or targets
    primary = [t for t in pool if t.primary]
    if len(primary) == 1:
        return primary[0]
    countries = {t.country for t in pool}
    cities = [t for t in pool if t.kind == "city"]
    if len(countries) == 1 and len(cities) == 1:
        # "Singapore", "Berlin", "New York": a city and its own country or state
        # share the name. The city is the more precise reading.
        city = cities[0]
        parents = [t for t in pool if t is not city]
        if all(t.kind == "country" or t.subdivision == city.subdivision for t in parents):
            return city
    if len(countries) == 1:  # e.g. "Washington": the state or D.C., but certainly the US
        return _Target("country", countries.pop())
    return None


def _most_specific(places: list[Place]) -> list[Place]:
    """Drop a country or state when a more specific place inside it was found."""

    def covered(p: Place) -> bool:
        return any(
            q is not p
            and q.country_code == p.country_code
            and (
                (p.subdivision is None and p.city is None and (q.subdivision or q.city))
                or (p.city is None and p.subdivision and q.subdivision == p.subdivision and q.city)
            )
            for q in places
        )

    return [p for p in places if not covered(p)]


@cache
def catalog() -> Catalog:
    return Catalog(json.loads(DATA_FILE.read_text(encoding="utf-8")))


def find_places(text: str, strict: bool = False) -> list[Place]:
    return catalog().scan(text, strict)[0]


def mentioned_regions(text: str) -> set[str]:
    """Countries covered by region words in ``text`` ("EMEA", "APAC", "GCC" …)."""
    return catalog().scan(text)[1]


def detect_work_mode(text: str) -> str | None:
    if not text:
        return None
    if HYBRID_PATTERN.search(text):
        return "hybrid"
    if REMOTE_PATTERN.search(text):
        return "remote"
    if ONSITE_PATTERN.search(text):
        return "onsite"
    return None


def summary() -> dict:
    cat = catalog()
    return {
        "source": cat.source,
        "regions": [{"id": r["id"], "name": r["name"], "kind": r["kind"]} for r in cat.regions.values()],
        "countries": len(cat.countries),
        "subdivisions": len(cat.subdivisions),
        "cities": sum(len(v) for v in cat.cities.values()),
    }
